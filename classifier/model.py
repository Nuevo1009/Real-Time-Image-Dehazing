import torch
import torch.nn as nn


class HazeCNN(nn.Module):

    def __init__(self):

        super(HazeCNN, self).__init__()


        # =====================================================
        # CONVOLUTION 1
        #
        # Input  : 3 channels (RGB)
        # Output : 8 feature maps
        # Kernel : 3 x 3
        # =====================================================

        self.conv1 = nn.Conv2d(

            in_channels=3,

            out_channels=8,

            kernel_size=3,

            padding=1

        )


        self.relu1 = nn.ReLU()


        # =====================================================
        # MAX POOLING
        #
        # 4 x 4
        # =====================================================

        self.pool = nn.MaxPool2d(

            kernel_size=4,

            stride=4

        )


        # =====================================================
        # DROPOUT 20%
        # =====================================================

        self.dropout1 = nn.Dropout(

            p=0.20

        )


        # =====================================================
        # CONVOLUTION 2
        #
        # Input  : 8 feature maps
        # Output : 16 feature maps
        # =====================================================

        self.conv2 = nn.Conv2d(

            in_channels=8,

            out_channels=16,

            kernel_size=3,

            padding=1

        )


        self.relu2 = nn.ReLU()


        # =====================================================
        # GLOBAL AVERAGE POOLING
        # =====================================================

        self.gap = nn.AdaptiveAvgPool2d(

            (1, 1)

        )


        # =====================================================
        # DROPOUT 30%
        # =====================================================

        self.dropout2 = nn.Dropout(

            p=0.30

        )


        # =====================================================
        # FULLY CONNECTED LAYER
        #
        # 16 → 8
        # =====================================================

        self.fc1 = nn.Linear(

            16,

            8

        )


        self.relu_fc1 = nn.ReLU()


        # =====================================================
        # OUTPUT LAYER
        #
        # 8 → 1
        # =====================================================

        self.fc2 = nn.Linear(

            8,

            1

        )


    # =========================================================
    # FORWARD PASS
    # =========================================================

    def forward(self, x):


        # -----------------------------------------------------
        # CONVOLUTION 1
        # -----------------------------------------------------

        x = self.conv1(x)

        x = self.relu1(x)


        # -----------------------------------------------------
        # MAX POOL
        # -----------------------------------------------------

        x = self.pool(x)


        # -----------------------------------------------------
        # DROPOUT
        # -----------------------------------------------------

        x = self.dropout1(x)


        # -----------------------------------------------------
        # CONVOLUTION 2
        # -----------------------------------------------------

        x = self.conv2(x)

        x = self.relu2(x)


        # -----------------------------------------------------
        # GLOBAL AVERAGE POOLING
        # -----------------------------------------------------

        x = self.gap(x)


        # -----------------------------------------------------
        # FLATTEN
        # -----------------------------------------------------

        x = torch.flatten(

            x,

            start_dim=1

        )


        # -----------------------------------------------------
        # DROPOUT
        # -----------------------------------------------------

        x = self.dropout2(x)


        # -----------------------------------------------------
        # FULLY CONNECTED
        # -----------------------------------------------------

        x = self.fc1(x)

        x = self.relu_fc1(x)


        # -----------------------------------------------------
        # FINAL OUTPUT
        # -----------------------------------------------------

        x = self.fc2(x)


        # -----------------------------------------------------
        # SIGMOID
        #
        # Output:
        # 0 → Clear
        # 1 → Hazy
        # -----------------------------------------------------

        x = torch.sigmoid(x)


        return x